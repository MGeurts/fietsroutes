/**
 * Retrieve pre-validated official GIS corridor between two knooppunten
 */
export function getOfficialGisCorridor(fromRef: string, toRef: string): {
  coordinates: [number, number][];
  distanceKm: number;
  source: string;
} | null {
  const directKey = `${fromRef}-${toRef}`;
  if (OFFICIAL_GIS_CORRIDORS[directKey]) {
    const c = OFFICIAL_GIS_CORRIDORS[directKey];
    return {
      coordinates: c.coordinates,
      distanceKm: c.distanceKm,
      source: c.source
    };
  }

  const reverseKey = `${toRef}-${fromRef}`;
  if (OFFICIAL_GIS_CORRIDORS[reverseKey]) {
    const c = OFFICIAL_GIS_CORRIDORS[reverseKey];
    return {
      // Reverse coordinates order for backwards traversal
      coordinates: [...c.coordinates].reverse(),
      distanceKm: c.distanceKm,
      source: c.source
    };
  }

  return null;
}
